#!/usr/bin/env node
/**
 * build.mjs — generate the CJS and UMD builds from the single ESM source.
 *
 * No bundler, no dependencies. The source is written so that every `export`
 * lives in one trailing block; this script strips that block, wraps the body,
 * and re-exports in the target format. It refuses to run if the source ever
 * grows an export statement somewhere else, so the transform cannot silently
 * drop code.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src', 'scanner-clock.js');
const OUT = join(root, 'dist');

const source = readFileSync(SRC, 'utf8');

const exportLines = source
  .split('\n')
  .map((line, i) => ({ line, n: i + 1 }))
  .filter(({ line }) => /^\s*(export|import)\b/.test(line));

const allowed = [
  'export { create, create as createScannerClock, simulate, VERSION, DEFAULTS };',
  'export default { create, createScannerClock: create, simulate, VERSION, DEFAULTS };',
];
for (const { line, n } of exportLines) {
  if (!allowed.includes(line.trim())) {
    console.error(`build: unexpected module statement at src/scanner-clock.js:${n}`);
    console.error(`  ${line.trim()}`);
    console.error('  Keep all exports in the trailing block, or update scripts/build.mjs.');
    process.exit(1);
  }
}

const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const srcVersion = /const VERSION = '([^']+)'/.exec(source)?.[1];
if (srcVersion !== version) {
  console.error(`build: VERSION in src (${srcVersion}) != package.json version (${version})`);
  process.exit(1);
}

const body = source
  .split('\n')
  .filter(line => !/^\s*export\b/.test(line))
  .join('\n')
  .trimEnd();

const banner = `/* scanner-clock v${version} — generated by scripts/build.mjs. Do not edit. */`;

mkdirSync(OUT, { recursive: true });

// The root package is `"type": "module"`, which would otherwise make the .js
// UMD file parse as ESM (its `typeof module` branch would miss, and a require()
// of it would come back empty). This scopes dist/ back to CommonJS. Browsers
// loading the UMD file with a <script> tag never see this and don't care.
writeFileSync(join(OUT, 'package.json'), JSON.stringify({ type: 'commonjs' }, null, 2) + '\n');

writeFileSync(join(OUT, 'scanner-clock.cjs'), `${banner}
'use strict';
${body}

const api = { create, createScannerClock: create, simulate, VERSION, DEFAULTS };
module.exports = api;
module.exports.create = create;
module.exports.createScannerClock = create;
module.exports.simulate = simulate;
module.exports.VERSION = VERSION;
module.exports.DEFAULTS = DEFAULTS;
module.exports.default = api;
`);

writeFileSync(join(OUT, 'scanner-clock.umd.js'), `${banner}
(function (root, factory) {
  if (typeof module === 'object' && module.exports) { module.exports = factory(); }
  else if (typeof define === 'function' && define.amd) { define([], factory); }
  else { root.ScannerClock = factory(); }
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';
${body}

  return {
    create: create, createScannerClock: create, simulate: simulate,
    VERSION: VERSION, DEFAULTS: DEFAULTS,
  };
});
`);

console.log(`built dist/scanner-clock.cjs and dist/scanner-clock.umd.js (v${version})`);
